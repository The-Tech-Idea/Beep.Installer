using System.Reflection;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace Beep.Installer.Core.Cli;

/// <summary>
/// The one owner of CLI verb metadata: which verbs exist, what they take, what they do to the
/// machine and whether they are offered over MCP.
///
/// The shell's verb table (<c>Program.Verbs</c>) owns <em>dispatch</em>; this owns <em>description</em>.
/// A guard test ties the two together, so a verb cannot be added to one without the other — the
/// same drift that once left several verbs unreachable behind the argument validator.
/// </summary>
public sealed class CliVerbCatalog
{
    private const string ResourceName = "Beep.Installer.Core.Cli.cli-catalog.json";

    private static readonly JsonSerializerOptions Json = new(JsonSerializerDefaults.Web)
    {
        PropertyNameCaseInsensitive = true,
        Converters = { new JsonStringEnumConverter(JsonNamingPolicy.KebabCaseLower, allowIntegerValues: false) },
        WriteIndented = true,
    };

    private static readonly Lazy<CliVerbCatalog> Shared = new(Load);

    private readonly CliCatalogDocument _document;

    private CliVerbCatalog(CliCatalogDocument document) => _document = document;

    /// <summary>The embedded catalog, parsed once.</summary>
    public static CliVerbCatalog Default => Shared.Value;

    public string Executable => _document.Executable;
    public IReadOnlyDictionary<string, string> ExitCodes => _document.ExitCodes;
    public IReadOnlyList<CliVerbDescriptor> Verbs => _document.Verbs;

    public IEnumerable<string> Categories => Verbs.Select(v => v.Category).Distinct(StringComparer.Ordinal);

    /// <summary>Finds a verb by id (<c>build</c>) or token/alias (<c>/BUILD=</c>, <c>/BUILD</c>, <c>/VERYSILENT</c>).</summary>
    public CliVerbDescriptor? Find(string idOrToken)
    {
        if (string.IsNullOrWhiteSpace(idOrToken)) return null;
        var key = idOrToken.Trim();
        return Verbs.FirstOrDefault(v =>
            string.Equals(v.Id, key, StringComparison.OrdinalIgnoreCase)
            || string.Equals(v.Token, key, StringComparison.OrdinalIgnoreCase)
            || string.Equals(v.Token.TrimEnd('='), key.TrimEnd('='), StringComparison.OrdinalIgnoreCase)
            || v.Aliases.Any(a => string.Equals(a, key, StringComparison.OrdinalIgnoreCase)));
    }

    public string ToJson() => JsonSerializer.Serialize(_document, Json);

    /// <summary>The catalog as Markdown, one table per category — what <c>/CATALOG /MARKDOWN</c> prints.</summary>
    public string ToMarkdown()
    {
        var sb = new StringBuilder();
        sb.AppendLine($"# {_document.Executable} command catalog");
        sb.AppendLine();
        sb.AppendLine("Generated from `cli-catalog.json`; do not edit by hand.");
        sb.AppendLine();
        sb.AppendLine("## Exit codes");
        sb.AppendLine();
        foreach (var (code, meaning) in _document.ExitCodes)
            sb.AppendLine($"- `{code}` — {meaning}");

        foreach (var category in Categories)
        {
            sb.AppendLine();
            sb.AppendLine($"## {category}");
            sb.AppendLine();
            sb.AppendLine("| Command | Effect | MCP | Summary |");
            sb.AppendLine("|---|---|---|---|");
            foreach (var verb in Verbs.Where(v => v.Category == category))
            {
                var usage = verb.Kind == CliVerbKind.Value ? $"{verb.Token}<{verb.Value?.Name ?? "value"}>" : verb.Token;
                var effect = verb.Effect.ToWireName();
                var mcp = verb.Mcp.Exposed ? "yes" : "no";
                sb.AppendLine($"| `{usage}` | {effect} | {mcp} | {verb.Summary.Replace("|", "\\|")} |");
            }
        }

        return sb.ToString();
    }

    /// <summary>Opening and closing markers of the generated region in <c>Help/cli-reference.html</c>.</summary>
    public const string HtmlBegin = "<!-- catalog:begin (generated by /CATALOG /HTML; do not edit by hand) -->";
    public const string HtmlEnd = "<!-- catalog:end -->";

    /// <summary>
    /// The catalog as the HTML section embedded in <c>Help/cli-reference.html</c>, between
    /// <see cref="HtmlBegin"/> and <see cref="HtmlEnd"/>. A guard test compares the page with this, so the
    /// reference cannot fall behind the verbs.
    /// </summary>
    public string ToHtml()
    {
        static string E(string text) => System.Net.WebUtility.HtmlEncode(text);

        var sb = new StringBuilder();
        sb.AppendLine(HtmlBegin);
        sb.AppendLine("<section class=\"section\">");
        sb.AppendLine("<h2>Complete command catalog</h2>");
        sb.AppendLine("<p>Every command, generated from <code>cli-catalog.json</code>. <em>Effect</em> says what it does to the machine; <em>MCP</em> says whether the <code>Beep.Installer.Mcp</code> server offers it.</p>");
        foreach (var category in Categories)
        {
            sb.AppendLine($"<h3>{E(category)}</h3>");
            sb.AppendLine("<table>");
            sb.AppendLine("<thead><tr><th>Command</th><th>Effect</th><th>MCP</th><th>What it does</th></tr></thead>");
            sb.AppendLine("<tbody>");
            foreach (var verb in Verbs.Where(v => v.Category == category))
            {
                var usage = verb.Kind == CliVerbKind.Value ? $"{verb.Token}&lt;{E(verb.Value?.Name ?? "value")}&gt;" : E(verb.Token);
                var aliases = verb.Aliases.Count == 0 ? "" : " · " + string.Join(" · ", verb.Aliases.Select(a => $"<code>{E(a)}</code>"));
                var options = verb.Options.Count == 0
                    ? ""
                    : "<br><small>" + string.Join(" ", verb.Options.Select(o =>
                        $"<code>{E(o.Name)}{(o.Required ? " (required)" : "")}{(o.Secret ? " (secret)" : "")}</code>")) + "</small>";
                var effect = verb.Effect.ToWireName();
                var mcp = verb.Mcp.Exposed ? "yes" : "no";
                sb.AppendLine($"<tr><td><code>{usage}</code>{aliases}{options}</td><td>{effect}</td><td>{mcp}</td><td>{E(verb.Summary)}</td></tr>");
            }
            sb.AppendLine("</tbody>");
            sb.AppendLine("</table>");
        }
        sb.AppendLine("</section>");
        sb.Append(HtmlEnd);
        return sb.ToString();
    }

    private static CliVerbCatalog Load()
    {
        using var stream = typeof(CliVerbCatalog).Assembly.GetManifestResourceStream(ResourceName)
            ?? throw new InvalidOperationException(
                $"The embedded CLI catalog '{ResourceName}' is missing from {typeof(CliVerbCatalog).Assembly.GetName().Name}; rebuild the project.");
        var document = JsonSerializer.Deserialize<CliCatalogDocument>(stream, Json)
            ?? throw new InvalidOperationException("The embedded CLI catalog is empty.");
        return new CliVerbCatalog(document);
    }
}
